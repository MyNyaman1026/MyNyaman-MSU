import { z } from "zod";
import { protectedProcedure, router } from "../_core/trpc";
import { TRPCError } from "@trpc/server";

// In-memory storage for codes (in production, use database)
// Structure: { code: string, parentId: number, used: boolean, createdAt: Date, expiresAt: Date }
const childLinkingCodes = new Map<
  string,
  {
    code: string;
    parentId: number;
    used: boolean;
    createdAt: Date;
    expiresAt: Date;
  }
>();

// Generate a unique 8-character alphanumeric code
function generateCode(): string {
  const chars = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789";
  let code = "";
  for (let i = 0; i < 8; i++) {
    code += chars.charAt(Math.floor(Math.random() * chars.length));
  }
  return code;
}

export const childLinkingRouter = router({
  // Generate a new child linking code
  generateCode: protectedProcedure.mutation(({ ctx }) => {
    if (ctx.user?.role !== "user") {
      throw new TRPCError({
        code: "FORBIDDEN",
        message: "Only parents can generate child linking codes",
      });
    }

    let code = generateCode();
    // Ensure code is unique
    while (childLinkingCodes.has(code)) {
      code = generateCode();
    }

    const expiresAt = new Date();
    expiresAt.setHours(expiresAt.getHours() + 24); // Code expires in 24 hours

    childLinkingCodes.set(code, {
      code,
      parentId: ctx.user.id,
      used: false,
      createdAt: new Date(),
      expiresAt,
    });

    return {
      code,
      expiresAt,
      message: "Child linking code generated successfully",
    };
  }),

  // Validate and use a child linking code
  validateCode: protectedProcedure
    .input(z.object({ code: z.string().length(8) }))
    .mutation(({ input, ctx }) => {
      const codeData = childLinkingCodes.get(input.code);

      if (!codeData) {
        throw new TRPCError({
          code: "NOT_FOUND",
          message: "Invalid code. Please check and try again.",
        });
      }

      // Allow code reuse - codes can be used multiple times
      // Only check expiration, not usage count

      if (new Date() > codeData.expiresAt) {
        throw new TRPCError({
          code: "BAD_REQUEST",
          message: "This code has expired. Please ask your parent for a new code.",
        });
      }

      // Code is reusable - no need to mark as used

      return {
        parentId: codeData.parentId,
        message: "Code validated successfully. You are now linked to your parent!",
      };
    }),

  // Get all codes generated by a parent
  getParentCodes: protectedProcedure.query(({ ctx }) => {
    if (ctx.user?.role !== "user") {
      throw new TRPCError({
        code: "FORBIDDEN",
        message: "Only parents can view their codes",
      });
    }

    const codes = Array.from(childLinkingCodes.values())
      .filter((c) => c.parentId === ctx.user?.id)
      .map((c) => ({
        code: c.code,
        used: c.used,
        createdAt: c.createdAt,
        expiresAt: c.expiresAt,
        isExpired: new Date() > c.expiresAt,
      }));

    return codes;
  }),

  // Revoke a code (parent can invalidate unused codes)
  revokeCode: protectedProcedure
    .input(z.object({ code: z.string().length(8) }))
    .mutation(({ input, ctx }) => {
      if (ctx.user?.role !== "user") {
        throw new TRPCError({
          code: "FORBIDDEN",
          message: "Only parents can revoke codes",
        });
      }

      const codeData = childLinkingCodes.get(input.code);

      if (!codeData) {
        throw new TRPCError({
          code: "NOT_FOUND",
          message: "Code not found",
        });
      }

      if (codeData.parentId !== ctx.user.id) {
        throw new TRPCError({
          code: "FORBIDDEN",
          message: "You can only revoke your own codes",
        });
      }

      childLinkingCodes.delete(input.code);

      return {
        message: "Code revoked successfully",
      };
    }),
});
